// Thanh token xếp chồng + popover chi tiết, DÙNG CHUNG cho mọi bảng có cột Tokens: popup AI Call Logs
// (agent-dashboard.js dựng ô bằng JS) và bảng "Cost by model" ở trang Usage (Razor dựng ô sẵn). Cả hai chỉ
// cần sinh ra một `.tok-cell` mang data-prompt / data-cached / data-cache-write / data-completion / data-total;
// file này lo phần còn lại (popover, hover/focus/Escape/cuộn). Script cổ điển: các hàm/hằng dưới đây là
// toàn cục để agent-dashboard.js gọi tokenBarHtml.
//
// Bốn đoạn của thanh là bốn phần RỜI NHAU của một lời gọi, cộng lại đúng bằng tổng:
//   cache read + cache write + uncached = prompt;  prompt + completion = total.
// Thứ tự đoạn cố định (đọc cache → ghi cache → input thường → output) để mắt so được giữa các dòng:
// phần xanh lá dài = prefix ổn định, phần xanh dương dài = phần prompt trả đủ giá input.
const TOKEN_SEGMENTS = [
    { key: 'cached', cls: 'seg-cache-read', label: 'Cache read', hint: 'Reused from the prompt cache' },
    { key: 'cacheWrite', cls: 'seg-cache-write', label: 'Cache write', hint: 'Stored in the cache for later calls' },
    { key: 'uncached', cls: 'seg-input', label: 'Uncached input', hint: 'Processed at the full input price' },
    { key: 'completion', cls: 'seg-output', label: 'Output', hint: 'Generated by the model' }
];

function formatPercent(part, whole) {
    return whole > 0 ? (Math.round(part * 1000 / whole) / 10).toFixed(1) + '%' : '0.0%';
}

// Thanh xếp chồng; đoạn > 0 luôn có tối thiểu 2px (CSS) để phần output 1% vẫn nhìn thấy được.
function tokenBarHtml(b, extraClass) {
    const sum = b.prompt + b.completion;
    if (sum <= 0) return `<div class="tok-bar ${extraClass || ''} is-empty"></div>`;
    const segs = TOKEN_SEGMENTS
        .filter(s => b[s.key] > 0)
        .map(s => `<span class="tok-seg ${s.cls}" style="flex-grow:${b[s.key]}"></span>`)
        .join('');
    return `<div class="tok-bar ${extraClass || ''}">${segs}</div>`;
}

function tokenPopoverHtml(b) {
    const row = s => {
        // Ba phần input tính % trên PROMPT (nên "Cache read" ở đây chính là tỉ lệ trúng cache, khớp số ở ô);
        // output chỉ có một dòng, không cần nhóm riêng, nên tính % trên tổng.
        const whole = s.key === 'completion' ? b.total : b.prompt;
        return `
            <div class="tok-pop-row">
                <span class="tok-dot ${s.cls}"></span>
                <span class="tok-pop-label">${s.label}<small>${s.hint}</small></span>
                <span class="tok-pop-num">${b[s.key].toLocaleString()}</span>
                <span class="tok-pop-pct">${formatPercent(b[s.key], whole)}</span>
            </div>`;
    };
    const inputRows = TOKEN_SEGMENTS.filter(s => s.key !== 'completion').map(row).join('');
    const outputRow = row(TOKEN_SEGMENTS[3]);
    const note = (b.cached === 0 && b.cacheWrite === 0)
        ? '<div class="tok-pop-note">No cache read or write reported.</div>'
        : '';
    return `
        <div class="tok-pop-head">
            <span>Token usage</span>
            <strong>${b.total.toLocaleString()}</strong>
        </div>
        ${tokenBarHtml(b, 'tok-bar-lg')}
        <div class="tok-pop-group is-first">
            <span>Input</span>
            <span class="tok-pop-num">${b.prompt.toLocaleString()}</span>
            <span class="tok-pop-pct">${formatPercent(b.prompt, b.total)}</span>
        </div>
        ${inputRows}
        <div class="tok-pop-sep"></div>
        ${outputRow}
        ${note}`;
}

// Popover là MỘT phần tử gắn thẳng vào <body>, định vị position:fixed theo ô đang hover. Không đặt
// trong ô được: bảng nằm trong khung overflow-x:auto của popup (cắt mọi thứ tràn ra ngoài), và
// popup là .modal-backdrop z-index 9999 nên popover phải nằm trên nó.
let tokenPopover = null;

function showTokenPopover(cell) {
    if (!tokenPopover) {
        tokenPopover = document.createElement('div');
        tokenPopover.className = 'tok-pop';
        tokenPopover.setAttribute('role', 'tooltip');
        tokenPopover.id = 'tok-pop';
        document.body.appendChild(tokenPopover);
    }
    const d = cell.dataset;
    const prompt = Number(d.prompt), cached = Number(d.cached), cacheWrite = Number(d.cacheWrite);
    const b = {
        prompt, cached, cacheWrite,
        uncached: Math.max(prompt - cached - cacheWrite, 0),
        completion: Number(d.completion),
        total: Number(d.total)
    };
    tokenPopover.innerHTML = tokenPopoverHtml(b);
    tokenPopover.classList.add('is-open');
    cell.setAttribute('aria-describedby', 'tok-pop');

    // Mặc định nằm dưới ô, canh trái theo ô; hết chỗ phía dưới thì lật lên trên, và luôn kẹp trong viewport.
    const r = cell.getBoundingClientRect();
    const pw = tokenPopover.offsetWidth, ph = tokenPopover.offsetHeight, gap = 8, margin = 8;
    let top = r.bottom + gap;
    if (top + ph > window.innerHeight - margin) top = Math.max(margin, r.top - gap - ph);
    let left = Math.min(r.left, window.innerWidth - pw - margin);
    tokenPopover.style.top = `${Math.round(top)}px`;
    tokenPopover.style.left = `${Math.round(Math.max(margin, left))}px`;
}

function hideTokenPopover(cell) {
    if (tokenPopover) tokenPopover.classList.remove('is-open');
    if (cell) cell.removeAttribute('aria-describedby');
}

// Uỷ quyền sự kiện ở document: tbody được dựng lại mỗi lần đổi trang/lọc, gắn listener theo ô thì
// phải gắn lại mỗi lần render.
document.addEventListener('mouseover', e => {
    const cell = e.target.closest && e.target.closest('.tok-cell:not(.is-empty)');
    if (cell && !cell.contains(e.relatedTarget)) showTokenPopover(cell);
});
document.addEventListener('mouseout', e => {
    const cell = e.target.closest && e.target.closest('.tok-cell');
    if (cell && !cell.contains(e.relatedTarget)) hideTokenPopover(cell);
});
document.addEventListener('focusin', e => {
    if (e.target.classList && e.target.classList.contains('tok-cell')) showTokenPopover(e.target);
});
document.addEventListener('focusout', e => {
    if (e.target.classList && e.target.classList.contains('tok-cell')) hideTokenPopover(e.target);
});
document.addEventListener('keydown', e => {
    if (e.key === 'Escape' && tokenPopover && tokenPopover.classList.contains('is-open')) hideTokenPopover();
});
// Popover định vị fixed theo toạ độ lúc mở — cuộn bảng/popup là toạ độ đó sai, nên đóng luôn.
document.addEventListener('scroll', () => hideTokenPopover(), true);
