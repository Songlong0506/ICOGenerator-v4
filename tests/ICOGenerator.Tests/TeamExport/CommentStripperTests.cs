using TeamExport.Stripping;
using Xunit;

namespace ICOGenerator.Tests.TeamExport;

// Bộ xoá comment chạy trên TOÀN BỘ source trước khi đưa sang repo team. Lỗi ở đây là lỗi âm thầm: một
// "//" trong URL bị coi là comment thì app bên team hỏng mà không ai thấy lúc review. Các test chốt
// những ca dễ nhầm nhất của từng ngôn ngữ.
public class CommentStripperTests
{
    private static readonly string[] Keep = ["<auto-generated"];

    [Fact]
    public void CSharp_RemovesAllCommentKindsButKeepsStringsThatLookLikeComments()
    {
        var src = """"
            // header
            namespace A;

            /// <summary>Doc.</summary>
            public class B
            {
                /* block */
                private const string Url = "http://x/*y*/"; // trailing
                private const string Raw = """
                    // not a comment
                    """;
                public int C(int a) => a /* inline */ + 1;
            }
            """";

        var result = CSharpCommentStripper.Strip(src, Keep);

        Assert.Equal(""""
            namespace A;

            public class B
            {
                private const string Url = "http://x/*y*/";
                private const string Raw = """
                    // not a comment
                    """;
                public int C(int a) => a + 1;
            }
            """", result);
    }

    [Fact]
    public void CSharp_KeepsAutoGeneratedMarker()
    {
        var src = "// <auto-generated />\n// other\nclass A { }\n";

        Assert.Equal("// <auto-generated />\nclass A { }\n", CSharpCommentStripper.Strip(src, Keep));
    }

    [Fact]
    public void CSharp_PreservesCrLf()
    {
        var src = "class A\r\n{\r\n    // x\r\n    int b; // y\r\n}\r\n";

        Assert.Equal("class A\r\n{\r\n    int b;\r\n}\r\n", CSharpCommentStripper.Strip(src, Keep));
    }

    [Fact]
    public void CSharp_InlineCommentBetweenTokensKeepsThemApart()
    {
        Assert.Equal("class A { int b = 1 + 2; }", CSharpCommentStripper.Strip("class A { int b = 1/**/+/**/2; }", Keep));
    }

    [Fact]
    public void JavaScript_DistinguishesRegexStringsAndTemplatesFromComments()
    {
        var src = """
            var re = /\/\/x/g; // c1
            var s = "// not";
            var t = `a ${ 1 /* c2 */ } // not`;
            /*! license */
            var d = 4 / 2; /* c3 */
            """;

        var result = JavaScriptCommentStripper.Strip(src, Keep);

        Assert.Equal("""
            var re = /\/\/x/g;
            var s = "// not";
            var t = `a ${ 1 } // not`;
            /*! license */
            var d = 4 / 2;
            """, result);
    }

    [Fact]
    public void Css_RemovesCommentsButNotInsideStrings()
    {
        var src = "/* a */\n.x { content: \"/* no */\"; color: red; /* b */ }\n";

        Assert.Equal(".x { content: \"/* no */\"; color: red; }\n", CssCommentStripper.Strip(src, Keep));
    }

    [Fact]
    public void Razor_RemovesRazorHtmlAndCodeBlockCommentsButNotUrlsInMarkup()
    {
        var src = """
            @model Foo
            @* razor comment *@
            @{
                // code comment
                var x = "http://a"; // trailing
                <p>http://inside-markup-in-code</p>
                @: line // with slashes
            }
            <!-- html comment -->
            <a href="https://example.com">https://example.com</a>
            @if (x != null)
            {
                // inside if
                <div>@x</div>
            }
            else
            {
                <span>// literal text</span>
            }
            """;

        var result = RazorCommentStripper.Strip(src, Keep);

        Assert.Equal("""
            @model Foo
            @{
                var x = "http://a";
                <p>http://inside-markup-in-code</p>
                @: line // with slashes
            }
            <a href="https://example.com">https://example.com</a>
            @if (x != null)
            {
                <div>@x</div>
            }
            else
            {
                <span>// literal text</span>
            }
            """, result);
    }

    [Fact]
    public void Razor_StripsJavaScriptCommentsInsideScriptWithRazorExpressions()
    {
        var src = """
            <script>
                window.A = '@Model.Id';
                // js comment
                window.B = @Html.Raw(Json("x // y"));
                window.C = @(ok ? "true" : "false"); /* c */
            </script>
            """;

        var result = RazorCommentStripper.Strip(src, Keep);

        Assert.Equal("""
            <script>
                window.A = '@Model.Id';
                window.B = @Html.Raw(Json("x // y"));
                window.C = @(ok ? "true" : "false");
            </script>
            """, result);
    }

    [Fact]
    public void Razor_TemplatedDelegateAndAttributesWithQuotesInsideRazor()
    {
        var src = """
            @{
                Func<int, object> card =
                @<div class="@(item > 1 ? "a" : "b")">
                    @* inner *@
                    <span>@item</span>
                </div>;
                // after
            }
            """;

        var result = RazorCommentStripper.Strip(src, Keep);

        Assert.Equal("""
            @{
                Func<int, object> card =
                @<div class="@(item > 1 ? "a" : "b")">
                    <span>@item</span>
                </div>;
            }
            """, result);
    }

    [Fact]
    public void Xml_RemovesCommentsButNotCData()
    {
        var src = "<Project>\n  <!-- c -->\n  <A><![CDATA[<!-- keep -->]]></A>\n</Project>\n";

        Assert.Equal("<Project>\n  <A><![CDATA[<!-- keep -->]]></A>\n</Project>\n", XmlCommentStripper.Strip(src, Keep));
    }

    [Fact]
    public void SpanRemover_CollapsesBlankLinesLeftByRemovedBlocks()
    {
        var src = "a\n\n// c1\n// c2\n\nb\n";
        var spans = new[] { new CommentSpan(3, 8), new CommentSpan(9, 14) };

        Assert.Equal("a\n\nb\n", CommentSpanRemover.Remove(src, spans));
    }
}
